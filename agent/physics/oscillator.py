def memory_goal(
    link: float,
    degree: int,
    acc: float,
    weight: float,
    current: float = 0.0,
    reference: float = MEMORY_REFERENCE,
) -> float:
    """Target of one link's memory (``basic.jl:312``).

    ``(link + N0 * acc / weight) / K`` — the start ``link`` plus the coincidence
    ``acc / weight`` (a weighted mean of ``cos``) read at the reference number
    of vibrations, divided by the degree ``K``: ``N`` in a full graph, ``z`` in
    a city. Full traction ``K * <W> = link + N0 * <cos>`` is O(1) in both.

    ``weight == 0`` means nothing was heard on this link; the memory keeps what
    it had (``current``), exactly as ``basic.jl:313`` does.
    """
    degree = int(degree)
    if degree < 1:
        raise ValueError("degree must be at least 1")
    weight = float(weight)
    if weight == 0.0:
        return float(current)
    return (float(link) + float(reference) * float(acc) / weight) / degree


def memory_step(coupling, target, epsilon: float, dt: float = 1.0):
    """One write of the memory: ``W += dt * eps * (target - W)`` (``basic.jl:358``).

    ``eps`` is the rate of the link; its lifetime is ``1 / eps``. Returns a new
    array; the caller's medium is left untouched.
    """
    coupling = np.asarray(coupling, dtype=float)
    target = np.asarray(target, dtype=float)
    return coupling + float(dt) * float(epsilon) * (target - coupling)


def step_state(
    omega,
    theta,
    coupling,
    omega0=None,
    *,
    link: float = 0.6,
    degree: Optional[int] = None,
    band: float = math.inf,
    memory: float = 0.0,
    tuning: float = 0.0,
    damping: float = 0.0,
    dt: float = 0.01,
    reference: float = MEMORY_REFERENCE,
):
    """One step of the book's law — ``step!`` (``basic.jl:317``).

    The order of operations is the book's, and it matters: the frequencies move
    first (the coupling pulls them), the phases then integrate the *new*
    frequencies, and the memory is written last, from the new state. Where the
    derivative is the law this is ``theta' = omega``, ``omega' = F``.

    Args:
        omega: ``(vibrations, modes)`` frequencies.
        theta: ``(vibrations, modes)`` phases.
        coupling: ``(vibrations, vibrations)`` written links; zero means "not
            neighbours", so the sparse structure of a city costs nothing.
        omega0: own frequencies the damping returns to (default: ``omega``).
        link: what the medium is written with (``basic.jl:143``).
        degree: ``K`` — number of neighbours; default ``N`` (full graph).
        band: Pi — resonance width, in the units of ``omega``.
        memory: eps — rate of the memory; 0 means "do not write".
        tuning: how firmly a chord keeps its overtones in ratio.
        damping: how firmly a vibration returns to its own frequency.
        dt: step of the description.
        reference: ``N0`` of the memory target.

    Returns:
        ``(omega, theta, coupling)`` — new arrays, the inputs are not modified.
    """
    omega = np.array(omega, dtype=float, copy=True)
    theta = np.array(theta, dtype=float, copy=True)
    coupling = np.array(coupling, dtype=float, copy=True)
    if omega.ndim != 2 or theta.shape != omega.shape:
        raise ValueError("omega and theta must be one layout: vibrations x modes")
    vibrations, modes = omega.shape
    if coupling.shape != (vibrations, vibrations):
        raise ValueError("coupling must be (vibrations, vibrations)")
    if omega0 is None:
        omega0 = np.array(omega, dtype=float, copy=True)
    else:
        omega0 = _as_matrix(omega0, "omega0")
        if omega0.shape != omega.shape:
            raise ValueError("omega0 must have the same shape as omega")
    k = vibrations if degree is None else int(degree)
    if k < 1:
        raise ValueError("degree must be at least 1")

    neighbours = [
        [j for j in range(vibrations) if j != i and coupling[i, j] != 0.0]
        for i in range(vibrations)
    ]

    # The force: what the medium pulls in each vibration — by frequency
    # coincidence (S) and by phase.
    drive = np.zeros((vibrations, modes), dtype=float)
    for i in range(vibrations):
        for p in range(modes):
            total = 0.0
            for j in neighbours[i]:
                for n in range(modes):
                    s = overlap(omega[j, n] - omega[i, p], band)
                    total += coupling[i, j] * s * math.sin(theta[j, n] - theta[i, p])
            drive[i, p] = total

    # Harmony and damping: an overtone holds to the root, a vibration to its own
    # frequency.
    for i in range(vibrations):
        for p in range(modes):
            if p > 0 and tuning != 0.0:
                # p + 1 is the book's harmonic number (the root frequency is 1).
                drive[i, p] -= tuning * (omega[i, p] - (p + 1) * omega[i, 0])
            if damping != 0.0:
                drive[i, p] -= damping * (omega[i, p] - omega0[i, p])

    omega = omega + dt * drive
    theta = theta + dt * omega

    # Memory: what passed through deforms the link; written last, from the new
    # state.
    if memory != 0.0:
        for i in range(vibrations):
            for j in neighbours[i]:
                acc, weight = 0.0, 0.0
                for p in range(modes):
                    for n in range(modes):
                        s = overlap(omega[j, n] - omega[i, p], band)
                        acc += s * math.cos(theta[i, p] - theta[j, n])
                        weight += s
                target = memory_goal(
                    link, k, acc, weight, coupling[i, j], reference=reference
                )
                coupling[i, j] = memory_step(coupling[i, j], target, memory, dt)
    return omega, theta, coupling
