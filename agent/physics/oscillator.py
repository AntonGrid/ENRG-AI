"""Entrain's oscillator algebra, ported to numpy (L3 physics, ENRG-AI).

A line-by-line port of the pure functions of ``entrain/julia/kuramoto/basic.jl``
— the reference implementation of the oscillator book. The book's state is
*frequency*; phase integrates frequency; what passed through a link deforms it
(the link's memory). Nothing here knows about Axis, proofs or watt-hours: this
module is the book's arithmetic and nothing else, so its numbers can be
compared with the Julia original one by one
(``tests/test_physics_oscillator.py`` against
``tests/fixtures/entrain_reference.json``, generated by ``julia 1.10.12``).

Arrays are read the same way as in Julia: ``(vibrations, modes)``. One producer
in a park is one vibration with one mode; a caller that wants chords passes
several modes. Wherever a function takes an ``index`` it answers for a single
vibration, otherwise it answers for all of them.

Differences from the Julia source — deliberate, local, and stated so nobody
mistakes them for physics:

* ``step_state`` is not in place: it returns new arrays, so a caller can keep
  reading the medium it just stepped (Julia's ``step!`` mutates its argument);
* per-link memory lifetimes (``memory_matrix``) and inner worlds (``inside``)
  are not ported — the park reads one lifetime per medium. Everything a park
  *reads* (S, R, Δθ, W) is here;
* ``omega`` columns are 0-based in Python; the harmony term ``p * omega[i, 1]``
  keeps the book's 1-based harmonic number, spelled out where it is used.

References are given as ``basic.jl:<line>`` in the checked-in source.
"""
from __future__ import annotations

import math
from typing import Optional

import numpy as np

#: Reference number of vibrations for the memory target (``basic.jl:66``). It is
#: not the size of the medium and not a scale by N: it says how many
#: coincidences the memory writes, so full traction ``K * W`` stays O(1).
MEMORY_REFERENCE = 10.0


def _as_matrix(values, name: str) -> np.ndarray:
    """Read a ``(vibrations, modes)`` array; a flat list is one vibration."""
    arr = np.asarray(values, dtype=float)
    if arr.ndim == 0:
        arr = arr.reshape(1, 1)
    if arr.ndim == 1:
        arr = arr.reshape(1, -1)
    if arr.ndim != 2:
        raise ValueError(f"{name} must be (vibrations, modes), got shape {arr.shape}")
    return arr


