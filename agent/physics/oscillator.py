def overlap(delta, band: float = math.inf):
    """``S(Δ) = 1 / (1 + (Δ/Π)²)`` — resonance by frequency coincidence
    (``basic.jl:243``).

    ``band`` is Π: a wide Π makes the medium answer to almost anything, a narrow
    one answers only to what sounds at its own frequency. ``Π = ∞`` is the
    "no selectivity" limit ``S ≡ 1``. Works elementwise, so it accepts a scalar
    or a whole difference matrix.
    """
    band = float(band)
    if math.isnan(band) or band <= 0.0:
        raise ValueError("band must be positive (or inf)")
    delta = np.asarray(delta, dtype=float)
    if math.isinf(band):
        return np.ones_like(delta)
    return 1.0 / (1.0 + (delta / band) ** 2)


def coherence(theta) -> float:
    """Order parameter ``R = |mean(e^{iθ})|`` (``basic.jl:378``).

    The mean runs over every pair (vibration, mode), as in the book: one phase
    per vibration, or a whole chord. ``R = 1`` — everything sounds together,
    ``R = 0`` — the phases are spread over the circle.
    """
    th = np.asarray(theta, dtype=float)
    if th.size == 0:
        return 0.0
    return float(abs(np.mean(np.exp(1j * th))))


def partial_coherence(theta, mode: Optional[int] = None):
    """Per-mode order parameter (``basic.jl:381``).

    For every mode, ``|mean over vibrations of e^{iθ}|`` — the same reading as
    :func:`coherence`, taken on one column of the chord. Returns one value per
    mode, or the value of ``mode`` when an index is given.
    """
    th = _as_matrix(theta, "theta")
    values = np.abs(np.mean(np.exp(1j * th), axis=0))
    return float(values[mode]) if mode is not None else values


def resonance(omega) -> float:
    """Width of the whole medium: ``max(omega) - min(omega)`` (``basic.jl:408``)."""
    om = np.asarray(omega, dtype=float)
    if om.size == 0:
        return 0.0
    return float(np.max(om) - np.min(om))


def spread(omega, index: Optional[int] = None):
    """Width of one vibration's chord (``basic.jl:415``).

    ``max - min`` across the modes of a vibration: zero means all modes sit on
    one frequency. Returns one value per vibration, or the value of ``index``.
    """
    om = _as_matrix(omega, "omega")
    values = np.max(om, axis=1) - np.min(om, axis=1)
    return float(values[index]) if index is not None else values


def chord(omega, theta, t: float = 0.0, index: Optional[int] = None):
    """Read one vibration's chord at time ``t`` (``basic.jl:393``):
    ``mean(cos(omega * t + theta))`` across its modes."""
    om = _as_matrix(omega, "omega")
    th = _as_matrix(theta, "theta")
    if om.shape != th.shape:
        raise ValueError(f"omega {om.shape} and theta {th.shape} must match")
    values = np.mean(np.cos(om * float(t) + th), axis=1)
    return float(values[index]) if index is not None else values


def wave(omega, theta, t: float = 0.0) -> float:
    """Read the whole medium at time ``t`` (``basic.jl:400``):
    ``mean(cos(omega * t + theta))`` over every pair (vibration, mode)."""
    om = _as_matrix(omega, "omega")
    th = _as_matrix(theta, "theta")
    if om.shape != th.shape:
        raise ValueError(f"omega {om.shape} and theta {th.shape} must match")
    return float(np.mean(np.cos(om * float(t) + th)))


def unison(omega, omega0, index: Optional[int] = None):
    """How far a chord has compressed (``basic.jl:423``).

    ``1 - spread(omega) / spread(omega0)``: zero — the width is what it was,
    one — every mode has converged to a single frequency. A chord that started
    on one frequency (width 0) cannot compress, so it reads 0.
    """
    om = _as_matrix(omega, "omega")
    ref = _as_matrix(omega0, "omega0")
    if om.shape != ref.shape:
        raise ValueError(f"omega {om.shape} and omega0 {ref.shape} must match")
    was = np.max(ref, axis=1) - np.min(ref, axis=1)
    safe = np.where(was == 0.0, 1.0, was)
    values = np.where(was == 0.0, 0.0, 1.0 - spread(om) / safe)
    return float(values[index]) if index is not None else values


def coincidence(theta, index: Optional[int] = None):
    """Phase coincidence inside one chord (``basic.jl:436``).

    Mean of ``cos(theta_p - theta_q)`` over the ordered pairs of a vibration:
    1 — the modes are in phase, 0 — spread, -1 — in antiphase. This is exactly
    what the inner memory writes: the relief goes to coincidence, not to ratio.
    """
    th = _as_matrix(theta, "theta")
    modes = th.shape[1]
    if modes < 2:
        return 0.0 if index is not None else np.zeros(th.shape[0])
    z = np.exp(1j * th)
    acc = np.abs(np.sum(z, axis=1)) ** 2 - modes
    values = acc / (modes * (modes - 1))
    return float(values[index]) if index is not None else values


